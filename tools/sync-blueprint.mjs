import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repository = "OpenAEC-Foundation/OpenAEC-Blueprint";
const revision = "436f3d78f02b3097000a6374c0dcdaf6854fc56b";
const destination = fileURLToPath(new URL("../apps/pile-plan-studio/src/openaec/", import.meta.url));
const manifestPath = join(destination, "manifest.json");
const fonts = ["Inter-Regular", "Inter-Medium", "Inter-SemiBold", "SpaceGrotesk-Medium", "SpaceGrotesk-Bold",
  "JetBrainsMono-Regular", "InterAEC-Regular", "InterAEC-Medium", "InterAEC-SemiBold", "NotoSans-Regular", "NotoSansSymbols-Regular"];
const sources = [
  ["web/openaec-tokens.css", "openaec-tokens.css"],
  ["web/openaec-fonts.css", "openaec-fonts.css"],
  ["web/openaec-components.css", "openaec-components.css"],
  ...["package.json", "README.md", "src/index.ts", "src/base.tsx", "src/controls.tsx", "src/feedback.tsx", "src/shell.tsx", "src/tiles.tsx"]
    .map(path => [`web/react/${path}`, `react/${path}`]),
  ["LICENSE", "LICENSE"],
  ["web/icons/manifest.json", "icons/upstream-manifest.json"],
  ["crates/openaec-icons/LICENSE.md", "icons/LICENSE.md"],
  ...fonts.flatMap(font => ["woff2", "ttf"].map(extension => [`web/fonts/${font}.${extension}`, `fonts/${font}.${extension}`])),
  ...["Inter", "SpaceGrotesk", "JetBrainsMono", "NotoSans"].map(font => [`web/fonts/${font}-OFL.txt`, `fonts/${font}-OFL.txt`]),
];
const sha256 = bytes => createHash("sha256").update(bytes).digest("hex");
const iconIds = ["file.save", "edit.undo", "edit.redo", "ui.settings", "ui.feedback",
  "project.properties", "data.apply", "ui.close", "object.unlock",
  "pile.cpt-settings", "pile.cost-settings", "pile.group-settings",
  "pile.load-points", "pile.cpts", "pile.load-groups", "edit.select", "pile.lock-edit", "pile.optimization",
  "view.grid", "panel.left", "panel.right", "file.open", "file.save-as", "file.import", "file.export",
  "file.type-ifc", "file.type-project", "file.type-other", "nav.back", "ui.about",
  "status.error", "status.warning", "status.success", "status.info",
  "object.rename", "edit.copy", "edit.delete", "pile.new", "table.column-filter",
  "pile.legend-used", "pile.legend-edit", "status.hidden"];
const iconSourceNames = ["reports", "composer", "standard", "pile-plan"];

function downloadSource(source) {
  const response = JSON.parse(execFileSync("gh", ["api", `repos/${repository}/contents/${source}?ref=${revision}`,
    "-H", "Accept: application/vnd.github+json"], { encoding: "utf8", maxBuffer: 16 * 1024 * 1024 }));
  if (response.encoding !== "base64") throw new Error(`Blueprint asset has no base64 content: ${source}`);
  return Buffer.from(response.content, "base64");
}

function createIconOutputs(sourceSprites) {
  const symbols = new Map();
  for (const sprite of sourceSprites) {
    for (const match of sprite.matchAll(/<symbol id="([^"]+)"[^>]*>[\s\S]*?<\/symbol>/g)) {
      symbols.set(match[1], match[0]);
    }
  }
  const selected = [];
  for (const id of iconIds) for (const size of [16, 24]) {
    const symbolId = `i${size}-${id}`;
    if (!symbols.has(symbolId)) throw new Error(`Blueprint source has no icon: ${symbolId}`);
    selected.push(symbols.get(symbolId));
  }
  return [
    { path: "icons/studio.svg", bytes: Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Generated by tools/sync-blueprint.mjs from Blueprint ${revision}. Do not edit. -->\n${selected.join("\n")}\n</svg>\n`) },
    { path: "icons/studioIcons.ts", bytes: Buffer.from(`// Generated by tools/sync-blueprint.mjs. Do not edit.\nexport const BLUEPRINT_ICON_IDS = ${JSON.stringify(iconIds)} as const;\nexport type BlueprintIconId = typeof BLUEPRINT_ICON_IDS[number];\n`) },
  ];
}

if (process.argv.includes("--check")) {
  const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  if (manifest.repository !== repository || manifest.revision !== revision || manifest.files.length !== sources.length) {
    throw new Error("Blueprint asset manifest does not match the pinned source.");
  }
  if (JSON.stringify(manifest.iconIds) !== JSON.stringify(iconIds)) throw new Error("Blueprint icon selection differs from the generated manifest.");
  for (const [source, path] of sources) {
    const entry = manifest.files.find(file => file.source === source && file.path === path);
    if (!entry || sha256(await readFile(join(destination, path))) !== entry.sha256) {
      throw new Error(`Blueprint asset differs from its source manifest: ${path}`);
    }
  }
  for (const path of ["icons/studio.svg", "icons/studioIcons.ts"]) {
    const entry = manifest.generated?.find(file => file.path === path);
    if (!entry || sha256(await readFile(join(destination, path))) !== entry.sha256) {
      throw new Error(`Generated Blueprint asset differs from its source manifest: ${path}`);
    }
  }
  const sprite = await readFile(join(destination, "icons/studio.svg"), "utf8");
  for (const id of iconIds) for (const size of [16, 24]) {
    if (!sprite.includes(`id="i${size}-${id}"`)) throw new Error(`Bundled Blueprint icon is missing: ${id} (${size})`);
  }
  console.log(`Blueprint ${revision.slice(0, 7)}: ${sources.length} shared assets and ${iconIds.length} interface icons verified.`);
} else {
  if (process.argv.length > 2) throw new Error("Usage: node tools/sync-blueprint.mjs [--check]");
  const files = [];
  for (const [source, path] of sources) {
    const bytes = downloadSource(source);
    const output = join(destination, path);
    await mkdir(dirname(output), { recursive: true });
    await writeFile(output, bytes);
    files.push({ source, path, sha256: sha256(bytes) });
  }
  const upstream = JSON.parse(await readFile(join(destination, "icons/upstream-manifest.json"), "utf8"));
  const iconSources = [];
  const sprites = [];
  for (const name of iconSourceNames) {
    const source = `web/icons/${upstream.apps[name].file}`;
    const bytes = downloadSource(source);
    if (sha256(bytes) !== upstream.apps[name].sha256) throw new Error(`Blueprint source sprite checksum failed: ${source}`);
    iconSources.push({ source, sha256: sha256(bytes) });
    sprites.push(bytes.toString("utf8"));
  }
  const generated = [];
  for (const { path, bytes } of createIconOutputs(sprites)) {
    await writeFile(join(destination, path), bytes);
    generated.push({ path, sha256: sha256(bytes) });
  }
  for (const oldPath of ["icons/titlebar.svg", "icons/titlebarIcons.ts"]) {
    await rm(join(destination, oldPath), { force: true });
  }
  await writeFile(manifestPath, JSON.stringify({ repository, revision, files, iconSources, iconIds, generated }, null, 2) + "\n");
  console.log(`Synced ${files.length} Blueprint assets and ${iconIds.length} interface icons from ${revision.slice(0, 7)}.`);
}
